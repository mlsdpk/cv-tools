"""The public API, the engine and the renderer details not covered elsewhere."""

import importlib.metadata
import subprocess

import pytest

import cv_tools
from cv_tools import api, engine
from cv_tools.markup import Latex
from cv_tools.model import ContactItem, ContactLine
from cv_tools.render.latex import AUTO_DATE, TEMPLATE_DIR, contact_line

from helpers import ROOT, SOURCE_DATE_EPOCH

MINIMAL = "version: 2\nname: Jane Roe\nsections: []\n"


def test_public_api():
    # pyproject.toml takes the version from cv_tools.__version__.
    assert importlib.metadata.version("cv-tools-cli") == cv_tools.__version__
    assert cv_tools.load is api.load
    assert set(cv_tools.__all__) >= {"load", "render_tex", "build_pdf", "migrate_text"}


def test_loads_resolves_bib_against_base_dir():
    text = "version: 2\nname: John Doe\nsections:\n  - {title: P, layout: publications, bib: publications.bib}\n"
    doc = api.loads(text, "inline.yaml", ROOT / "examples")
    assert doc.sections[0].bib == (ROOT / "examples" / "publications.bib").resolve()
    assert doc.sections[0].highlight == ["John Doe"]
    assert len(doc.sections[0].publications) == 7


def test_render_result_files():
    result = api.render_tex(api.loads(MINIMAL))
    assert result.files == {
        "resume.cls": (TEMPLATE_DIR / "resume.cls").read_bytes(),
        "orcid.pdf": (TEMPLATE_DIR / "orcid.pdf").read_bytes(),
    }
    assert result.tex.startswith(f"% Generated by cv-tools {cv_tools.__version__}.")


def test_class_has_no_tikz():
    cls = (TEMPLATE_DIR / "resume.cls").read_text(encoding="utf-8")
    for package in ("tikz", "pgf", "scalerel", "academicons"):
        assert f"{{{package}}}" not in cls
    assert "\\includegraphics" in cls


def test_three_contact_lines_print_in_order():
    # resume.cls prints its third \address first, so the renderer emits 2, 3, 1.
    doc = api.loads("version: 2\nname: x\ncontact: [[a], [b], [c]]\n")
    tex = api.render_tex(doc).tex
    assert [line for line in tex.splitlines() if line.startswith("\\address")] == [
        "\\address{b}", "\\address{c}", "\\address{a}",
    ]


@pytest.mark.parametrize(
    "line, latex",
    [
        (ContactLine([]), ""),
        (ContactLine([ContactItem("text", "a"), ContactItem("text", "b")]), r"a \\ b"),
        (ContactLine([ContactItem("text", "a"), ContactItem("github", "https://g")]), r"a \href{https://g}{\colorfaGithub}"),
        (ContactLine([ContactItem("orcid", "0000"), ContactItem("text", "b")]), r"\orcidicon{0000} \\ b"),
        (ContactLine([ContactItem("text", "a"), ContactItem("url", "https://u/%")], " "), r"a \url{https://u/\%}"),
        (ContactLine([ContactItem("text", "a"), ContactItem("text", "b")], " · "), "a · b"),
        (ContactLine([ContactItem("text", "a"), ContactItem("text", "b")], Latex(" $\\cdot$ ")), r"a $\cdot$ b"),
        (ContactLine([ContactItem("url", Latex(r"\x")), ContactItem("twitter", "t")]), r"\url{\x} \href{t}{\colorfaTwitter}"),
        (ContactLine([ContactItem("text", "CV, {date}"), ContactItem("text", Latex("{date}"))]), r"CV, \customdate\today{} \\ {date}"),
    ],
)
def test_contact_line(line, latex):
    assert contact_line(line, AUTO_DATE) == latex


def test_literal_date_is_escaped():
    doc = api.loads("version: 2\nname: x\ndate: 1 May 2025 & later\ncontact: [['{date}']]\n")
    assert "\\address{1 May 2025 \\& later{}}" in api.render_tex(doc).tex


@pytest.mark.tex
def test_build_pdf_is_deterministic_and_dated(tmp_path):
    doc = api.load(ROOT / "examples" / "cv.yaml")
    out = tmp_path / "cv.pdf"
    first = api.build_pdf(doc, out=out, source_date_epoch=SOURCE_DATE_EPOCH)
    assert out.read_bytes() == first
    assert api.build_pdf(doc, source_date_epoch=SOURCE_DATE_EPOCH) == first
    text = subprocess.run(["pdftotext", str(out), "-"], capture_output=True, text=True).stdout
    assert "Curriculum Vitae, 14th November 2023" in text


def test_engine_errors(monkeypatch):
    result = api.render_tex(api.loads(MINIMAL))
    with pytest.raises(engine.EngineError, match="unknown engine 'xelatex'"):
        engine.compile_pdf(result, engine="xelatex")
    monkeypatch.setattr(engine, "find_pdflatex", lambda: None)
    with pytest.raises(engine.EngineError, match="pdflatex not found"):
        api.build_pdf(api.loads(MINIMAL), engine="pdflatex")
    monkeypatch.setattr(engine.doctor, "check_docker", lambda: engine.doctor.DockerStatus(None, False, "not found"))
    with pytest.raises(engine.EngineError, match="pdflatex was not found, and Docker is not installed"):
        api.build_pdf(api.loads(MINIMAL))


def test_compile_env(monkeypatch):
    monkeypatch.delenv("SOURCE_DATE_EPOCH", raising=False)
    monkeypatch.delenv("FORCE_SOURCE_DATE", raising=False)
    assert "SOURCE_DATE_EPOCH" not in engine.compile_env()
    e = engine.compile_env(1234)
    assert (e["SOURCE_DATE_EPOCH"], e["FORCE_SOURCE_DATE"]) == ("1234", "1")
    monkeypatch.setenv("SOURCE_DATE_EPOCH", "99")
    assert engine.compile_env()["SOURCE_DATE_EPOCH"] == "99"


def test_log_errors():
    log = "This is pdfTeX\n(./cv.tex\n! Undefined control sequence.\nl.5 \\foo\n\nmore\nrest\n"
    assert engine.log_errors(log) == "! Undefined control sequence.\nl.5 \\foo\n\nmore"
    assert engine.log_errors("no errors\nhere") == "no errors\nhere"


@pytest.mark.parametrize(
    "log, found",
    [
        ("! Undefined control sequence.\n<recently read> \\tikz \n   \nl.15 \\item \\tikz\n", "\\tikz"),
        ("! Undefined control sequence.\n\\@addresstwo ->\\scaleobj \n\nl.11 \\begin{document}\n", "\\scaleobj"),
        ("! Undefined control sequence.\nl.14 a \\pgfmathsetmacro\n  b \\\\\n", "\\pgfmathsetmacro"),
        ("! LaTeX Error: Environment tikzpicture undefined.\n", "the tikzpicture environment"),
        # Other commands, or a removed name that is not the undefined one.
        ("! Undefined control sequence.\nl.14 \\tikzx\n", None),
        ("! Undefined control sequence.\nl.14 \\TIKZ\n", None),
        ("! Undefined control sequence.\nl.14 \\foo\n\\tikz\n", None),
        ("! LaTeX Error: Environment tikzcd undefined.\n", None),
        ("! Missing $ inserted.\n<inserted text> \\tikz\n", None),
        ("no error at all\n", None),
    ],
)
def test_removed_command(log, found):
    assert engine.removed_command(log) == found


def test_write_tex(tmp_path):
    result = api.render_tex(api.loads(MINIMAL))
    written = engine.write_tex(result, tmp_path / "sub" / "my.tex")
    assert [p.name for p in written] == ["my.tex", "resume.cls", "orcid.pdf"]
    assert (tmp_path / "sub" / "my.tex").read_text(encoding="utf-8") == result.tex


def test_test_helpers_compile_with_the_local_pdflatex(monkeypatch):
    # With engine "auto" a test could fall back to Docker and compare PDFs of two TeX installations.
    import helpers

    engines = []
