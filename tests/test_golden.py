"""Golden .tex and PDF facts (pages, links, text) for every v2 layout.

Update them with ``pytest tests/test_golden.py --update-golden`` and review the diff.
"""

import json
import re
import unicodedata

import pytest
from pypdf import PdfReader

from cv_tools import api

from helpers import FIXTURES, TESTS, compile_result, link_targets, page_count

GOLDEN = TESTS / "golden"
CASES = sorted((FIXTURES / "v2").glob("*.yaml"))
VERSION_LINE = re.compile(r"\A% Generated by cv-tools [^\n]*\n")


def without_version(tex: str) -> str:
    assert VERSION_LINE.match(tex), tex[:80]
    return VERSION_LINE.sub("", tex, count=1)


@pytest.mark.parametrize("path", CASES, ids=lambda p: p.stem)
def test_golden_tex(path, update_golden):
    tex = api.render_tex(api.load(path)).tex
    golden = GOLDEN / f"{path.stem}.tex"
    if update_golden:
        golden.write_text(tex, encoding="utf-8")
        pytest.skip("golden file updated")
    assert golden.exists(), f"missing {golden}; run pytest --update-golden"
    assert without_version(tex) == without_version(golden.read_text(encoding="utf-8"))


def test_version_line_is_ignored():
    a = "% Generated by cv-tools 2.0.0. Compile with pdflatex.\n\\documentclass{resume}\n"
    b = "% Generated by cv-tools 2.1.0. Compile with pdflatex.\n\\documentclass{resume}\n"
    assert without_version(a) == without_version(b)
    assert without_version(a) != without_version(a.replace("resume", "article"))


def test_no_stale_golden_files():
    stems = sorted(p.stem for p in CASES)
    assert sorted(p.stem for p in GOLDEN.glob("*.tex")) == stems
    assert sorted(p.name[: -len(".pdf.json")] for p in GOLDEN.glob("*.pdf.json")) == stems


def pdf_text(pdf: bytes) -> str:
    """The PDF text, normalized so line breaking does not matter."""
    import io

    raw = "\n".join(page.extract_text() or "" for page in PdfReader(io.BytesIO(pdf)).pages)
    text = unicodedata.normalize("NFKC", raw)
    text = re.sub(r"-\s*\n\s*", "", text)
    return " ".join(text.split())


def pdf_facts(pdf: bytes) -> dict:
    return {"pages": page_count(pdf), "links": link_targets(pdf), "text": pdf_text(pdf)}


@pytest.mark.tex
@pytest.mark.parametrize("path", CASES, ids=lambda p: p.stem)
def test_golden_pdf(path, update_golden):
    facts = pdf_facts(compile_result(api.render_tex(api.load(path))))
    golden = GOLDEN / f"{path.stem}.pdf.json"
    if update_golden:
        golden.write_text(json.dumps(facts, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        pytest.skip("golden file updated")
    assert golden.exists(), f"missing {golden}; run pytest --update-golden"
    expected = json.loads(golden.read_text(encoding="utf-8"))
    assert facts["pages"] == expected["pages"]
    assert facts["links"] == expected["links"]
    assert facts["text"] == expected["text"]
