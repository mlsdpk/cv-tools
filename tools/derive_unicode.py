r"""Derive src/cv_tools/templates/latex/unicode.txt, the non-ASCII characters pdflatex can print.

Run it after changing resume.cls or TeX Live (--check exits 1 if it is stale).
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LATEX_DIR = ROOT / "src" / "cv_tools" / "templates" / "latex"
OUTPUT = LATEX_DIR / "unicode.txt"
HEADER = (
    "# Non-ASCII characters that pdflatex prints in a cv-tools document, one code point per line.\n"
    "# Generated by tools/derive_unicode.py from the .dfu files of TeX Live and resume.cls;\n"
    "# do not edit by hand.\n"
)

DECLARATION = re.compile(r"^[^%\n]*\\DeclareUnicodeCharacter\s*\{([0-9A-Fa-f]{4,6})\}", re.M)


def run_pdflatex(tex: str, directory: Path) -> str:
    for name in ("resume.cls", "orcid.pdf"):
        shutil.copy(LATEX_DIR / name, directory / name)
    (directory / "t.tex").write_text(tex, encoding="utf-8")
    subprocess.run(["pdflatex", "-interaction=nonstopmode", "t.tex"], cwd=directory, capture_output=True)
    return (directory / "t.log").read_text(encoding="utf-8", errors="replace")


def font_encodings(directory: Path) -> list[str]:
    log = run_pdflatex(
        "\\documentclass{resume}\n\\makeatletter\n"
        "\\def\\cdp@elt#1#2#3#4{\\typeout{CV-TOOLS-ENCODING #1}}\\cdp@list\n"
        "\\makeatother\n\\begin{document}\nx\n\\end{document}\n",
        directory,
    )
    return re.findall(r"^CV-TOOLS-ENCODING (\S+)$", log, re.M)


def kpsewhich(name: str) -> Path | None:
    out = subprocess.run(["kpsewhich", name], capture_output=True, text=True).stdout.strip()
    return Path(out) if out else None


def declared(path: Path) -> set[int]:
    return {int(cp, 16) for cp in DECLARATION.findall(path.read_text(encoding="utf-8", errors="replace"))}


def latex_declarations(directory: Path) -> tuple[set[int], list[str]]:
    files = [kpsewhich(f"{enc.lower()}enc.dfu") for enc in font_encodings(directory)] + [kpsewhich("utf8.def")]
    found = [f for f in files if f is not None]
    return set().union(*(declared(f) for f in found)), [f.name for f in found]


PROBE = r"""\documentclass{resume}
\tracinglostchars=1
\begin{document}
%s
\typeout{CV-TOOLS-END}
\end{document}
"""


def _passing(log: str) -> set[int]:
    if "CV-TOOLS-END" not in log:
        sys.exit("derive_unicode.py: the probe document did not finish")
    ok = set()
    for block in re.split(r"^CV-TOOLS-CHAR ", log, flags=re.M)[1:]:
        cp, _, rest = block.partition("\n")
        if not re.search(r"^! |Missing character", rest, re.M):
            ok.add(int(cp, 16))
    return ok


def _probe(code_points: set[int], typeset, directory: Path) -> set[int]:
    body = "\n".join(f"\\typeout{{CV-TOOLS-CHAR {cp:04X}}}\\leavevmode\\setbox0\\hbox{{{typeset(chr(cp))}}}\\par"
                     for cp in sorted(code_points))
    return _passing(run_pdflatex(PROBE % body, directory))


# A declared character can still fail in the OT1 font (ð is \dh, which only T1 has).
def printable(candidates: set[int], directory: Path) -> set[int]:
    return _probe(candidates, lambda c: f"{c} \\textbf{{{c}}} \\textit{{{c}}}", directory)


def uppercase_problems(ok: set[int], directory: Path) -> list[str]:
    # cv-tools checks upper-cased titles with str.upper, so TeX must print those forms too.
    upper_ok = _probe(ok, lambda c: f"\\MakeUppercase{{{c}}}", directory)
    problems = []
    for cp in sorted(ok):
        predicted = all(ord(u) < 0x80 or ord(u) in ok for u in chr(cp).upper())
        if predicted and cp not in upper_ok:
            problems.append(f"U+{cp:04X} fails in \\MakeUppercase, but its str.upper form is kept")
    return problems


def derive() -> tuple[str, list[str]]:
    with tempfile.TemporaryDirectory() as tmp:
        directory = Path(tmp)
        latex, sources = latex_declarations(directory)
        ours = declared(LATEX_DIR / "resume.cls")
        problems = [f"resume.cls declares U+{cp:04X}, which {', '.join(sources)} already declare"
                    for cp in sorted(ours & latex)]
        candidates = {cp for cp in latex | ours if cp > 0x7F}
        ok = printable(candidates, directory)
        problems += uppercase_problems(ok, directory)
    lines = [f"{cp:04X} # {chr(cp) if unicodedata.category(chr(cp))[0] != 'C' else ' '} "
             f"{unicodedata.name(chr(cp), '')}".rstrip() for cp in sorted(ok)]
    text = HEADER + f"# Sources: {', '.join(sources)} and resume.cls.\n" + "\n".join(lines) + "\n"
    return text, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that unicode.txt is up to date")
    args = parser.parse_args()
    text, problems = derive()
    for problem in problems:
        print(f"derive_unicode.py: {problem}", file=sys.stderr)
    if problems:
        return 1
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is stale; run tools/derive_unicode.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({text.count(chr(10)) - text.count(chr(10) + '#') - 1} characters)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
