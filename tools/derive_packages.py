"""Derive src/cv_tools/templates/latex/packages.txt from a pdflatex -recorder run.

Run it after changing resume.cls, the templates or unicode.txt (--check exits 1 if it is stale).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from cv_tools import api, charset, engine

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "cv_tools" / "templates" / "latex" / "packages.txt"
DOCUMENTS = [ROOT / "examples" / "cv.yaml", ROOT / "tests" / "fixtures" / "v2" / "contact.yaml"]
HEADER = (
    "# TeX Live packages that cv-tools documents load with pdflatex.\n"
    "# Generated by tools/derive_packages.py from a -recorder run; do not edit by hand.\n"
)


TREES = ("TEXMFDIST", "TEXMFHOME", "TEXMFLOCAL", "TEXMFSYSVAR", "TEXMFVAR", "TEXMFSYSCONFIG", "TEXMFCONFIG")


def kpse_var(name: str) -> str:
    out = subprocess.run(["kpsewhich", "-var-value", name], capture_output=True, text=True, check=True)
    return out.stdout.strip()


def texmf_trees() -> list[Path]:
    return [Path(kpse_var(t)).expanduser().resolve() for t in TREES if kpse_var(t)]


def file_owners(tlpdb: Path) -> dict[str, str]:
    owners: dict[str, str] = {}
    package, in_runfiles = None, False
    for line in tlpdb.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("name "):
            package, in_runfiles = line[5:].strip(), False
        elif line.startswith("runfiles"):
            in_runfiles = True
        elif line.startswith(" ") and in_runfiles and package and "." not in package:
            owners[line.split()[0]] = package
        elif not line.startswith(" "):
            in_runfiles = False
    return owners


def unicode_document() -> api.Document:
    chars = "".join(chr(cp) for cp in sorted(charset.supported()))
    entries = [json.dumps(chars), json.dumps(f"**{chars}**"), json.dumps(f"*{chars}*"), json.dumps(f"***{chars}***")]
    text = "version: 2\nname: x\nsections:\n  - title: T\n    layout: list\n    entries:\n"
    return api.loads(text + "".join(f"      - {e}\n" for e in entries))


def recorded_inputs(doc: api.Document) -> set[Path]:
    result = api.render_tex(doc)
    with tempfile.TemporaryDirectory() as tmp:
        engine.write_tex(result, Path(tmp) / "cv.tex")
        subprocess.run(
            [engine.find_pdflatex() or "pdflatex", "-recorder", "-interaction=nonstopmode", "-halt-on-error", "cv.tex"],
            cwd=tmp, capture_output=True, check=True,
        )
        lines = (Path(tmp) / "cv.fls").read_text(encoding="utf-8").splitlines()
    return {Path(line[6:]).resolve() for line in lines if line.startswith("INPUT ") and line[6:].startswith("/")}


def derive() -> str:
    owners = file_owners(Path(kpse_var("TEXMFROOT")) / "tlpkg" / "texlive.tlpdb")
    trees = texmf_trees()
    packages = set()
    for doc in [api.load(path) for path in DOCUMENTS] + [unicode_document()]:
        for path in recorded_inputs(doc):
            for tree in trees:
                if path.is_relative_to(tree):
                    # tlpdb lists files relative to texmf-dist, whichever tree holds them here.
                    package = owners.get("texmf-dist/" + path.relative_to(tree).as_posix())
                    if package:
                        packages.add(package)
                    break
    return HEADER + "".join(f"{p}\n" for p in sorted(packages))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = derive()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date; run tools/derive_packages.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
