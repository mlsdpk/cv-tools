"""Write the documents the engine trees are recorded from. Usage: python -I coverage.py <repo root> <out dir>"""

from __future__ import annotations

import json
import re
import sys
import warnings
from pathlib import Path

from cv_tools import api, charset
from cv_tools.markup import to_latex
from cv_tools.render import latex as render_latex

# Font selections the templates and the markup produce, as (prefix, suffix).
SHAPES = {
    "upright": ("", ""),
    "bold": (r"\textbf{", "}"),
    "italic": (r"\textit{", "}"),
    "bold italic": (r"\textbf{\textit{", "}}"),
    "emph in italic": (r"\textit{\emph{", "}}"),
    "typewriter": (r"\texttt{", "}"),
}
CONTEXTS = [  # (size, shapes)
    (r"\normalsize", ["upright", "bold", "italic", "bold italic", "emph in italic", "typewriter"]),
    (r"\huge", ["bold", "bold italic"]),
]

# Every size the .fd files declare; LaTeX substitutes any other size with one of these.
SIZE_COMMANDS = [r"\tiny", r"\scriptsize", r"\footnotesize", r"\small", r"\normalsize",
                 r"\large", r"\Large", r"\LARGE", r"\huge", r"\Huge"]
SIZES = ["5", "6", "7", "8", "9", "10", "10.95", "12", "14.4", "17.28", "20.74", "24.88"]
EC_SIZES = SIZES + ["29.86", "35.83"]
SERIES = ["m", "b", "bx", "sbc"]
# No sbc: cm-super's ecssdc10 exists only as METAFONT source, so the browser
# engine reports it missing.
EC_SERIES = ["m", "b", "bx"]
FONT_SHAPES = ["n", "it", "sl", "sc", "ui", "scsl"]
# Encodings and families raw LaTeX reaches without packages.
BASE_ENCODINGS = [
    ("OT1", ["cmr", "cmss", "cmtt"]),
    ("OML", ["cmm", "cmr", "cmss", "cmtt"]),
    ("OMS", ["cmsy", "cmr", "cmss", "cmtt"]),
    ("OMX", ["cmex"]),
]
EXTRA_ENCODINGS = [("T1", ["cmr", "cmss", "cmtt"]), ("TS1", ["cmr", "cmss", "cmtt"])]
MATH = (r"$x^{2^{y}}_{i_j}+\alpha\Gamma\sum_{k=1}^n\int_0^1\sqrt{y}\prod\bigcup\langle a\rangle"
        r"\mathcal{O}\mathbf{x}\mathsf{x}\mathtt{x}\mathit{x}\mathrm{x}\mathnormal{x}\left(\frac{a}{b}\right)\Bigl[\Bigr]$ "
        r"$\displaystyle\sum_{k}\int\bigotimes\coprod\Bigl(\frac{1}{2}\Bigr)$")


def font_matrix(encodings: list[tuple[str, list[str]]], sizes: list[str], series_list: list[str]) -> list[str]:
    """One font selection per encoding, family, series, shape and size."""
    lines = []
    for enc, families in encodings:
        for family in families:
            for series in series_list:
                for shape in FONT_SHAPES:
                    sel = "".join(rf"{{\fontsize{{{s}}}{{{s}}}\usefont{{{enc}}}{{{family}}}{{{series}}}{{{shape}}}A}}" for s in sizes)
                    lines.append(f"% {enc} {family} {series} {shape}\n{sel}\\par")
    return lines


def document(body: list[str], icons: str = "") -> str:
    return "\n".join([
        "% cv-tools web engine coverage document (generated by web/engine/coverage.py).",
        r"\documentclass{resume}",
        r"\name{Coverage}",
        r"\address{" + icons + "}",
        r"\begin{document}",
        *body,
        r"\end{document}",
        "",
    ])


def cases(root: Path) -> list[tuple[str, Path]]:
    fixtures = sorted((root / "tests" / "fixtures" / "v2").glob("*.yaml"))
    found = [(f"fixture-{p.stem}", p) for p in fixtures]
    found += [("example", root / "examples" / "cv.yaml"), ("example-v1", root / "examples" / "v1" / "cv.yaml")]
    missing = [str(p) for _, p in found if not p.is_file()]
    if missing or not fixtures:
        raise SystemExit(f"coverage.py: missing inputs: {missing or 'tests/fixtures/v2/*.yaml'}")
    return found


def write_case(directory: Path, tex: str, files: dict[str, bytes]) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "cv.tex").write_bytes(tex.encode("utf-8"))
    for name, data in files.items():
        (directory / name).write_bytes(data)


def declared(cls: str) -> set[int]:
    return {int(m, 16) for m in re.findall(r"\\DeclareUnicodeCharacter\{([0-9A-Fa-f]+)\}", cls)}


def synthetic(files: dict[str, bytes]) -> str:
    cls = files["resume.cls"].decode("utf-8")
    code_points = sorted(charset.supported() | declared(cls))
    ascii_chars = [chr(c) for c in range(0x21, 0x7F)]
    chars = ascii_chars + [chr(c) for c in code_points]
    # Convert one character at a time so markup characters print as themselves.
    text = " ".join(to_latex(c) for c in chars)
    # Names and section titles are upper-cased.
    upper = " ".join(to_latex(c) for c in chars if all(charset.prints(u) for u in c.upper()))
    date = render_latex.AUTO_DATE + "{}"
    body = []
    for size, shapes in CONTEXTS:
        for shape in shapes:
            pre, post = SHAPES[shape]
            body.append(f"% {size} {shape}")
            body.append(f"{{{size} {pre}{text}{post}\\par}}")
            body.append(f"{{{size} {pre}\\MakeUppercase{{{upper}}}{post}\\par}}")
            body.append(f"{{{size} {pre}Updated {date} {to_latex('~')}{post}\\par}}")
    icons = r"\colorfaLinkedinSquare{} \colorfaGithub{} \colorfaTwitter{} \orcidicon{0000-0002-1825-0097}"
    fa = r"{\FAone A}{\FAtwo A}{\FAthree A}"
    links = r"\url{https://example.org/a_b-c~d%20e?f=g&h=i#j} \href{https://example.org/}{[Link]}"
    math = [f"{{{size} {MATH} {{\\boldmath {MATH}}}\\par}}" for size in SIZE_COMMANDS]
    return document([
        r"\begin{rSection}{Fonts}",
        *body,
        r"\end{rSection}",
        r"\begin{rSection}{Icons and links}",
        icons + r"\par",
        r"{\large " + fa + r"} {\normalsize " + fa + r"}\par",
        links + r"\par",
        r"\end{rSection}",
        r"\begin{rSection}{Font matrix}",
        *font_matrix(BASE_ENCODINGS, SIZES, SERIES),
        r"\end{rSection}",
        r"\begin{rSection}{Math}",
        *math,
        r"\end{rSection}",
    ], icons)


def extras() -> str:
    """The T1 and TS1 matrix (cm-super) for the on-demand font pack."""
    return document(font_matrix(EXTRA_ENCODINGS, EC_SIZES, EC_SERIES))


def main(argv: list[str]) -> None:
    root, out = Path(argv[0]).resolve(), Path(argv[1]).resolve()
    written = []
    support: dict[str, bytes] = {}
    for name, path in cases(root):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", DeprecationWarning)
            result = api.render_tex(api.load(path))
        write_case(out / name, result.tex, result.files)
        support = result.files
        written.append(str(out / name))
    write_case(out / "synthetic", synthetic(support), support)
    written.append(str(out / "synthetic"))
    write_case(out / "extras", extras(), support)
    print(json.dumps({"base": written, "extras": [str(out / "extras")]}))


if __name__ == "__main__":
    main(sys.argv[1:])
